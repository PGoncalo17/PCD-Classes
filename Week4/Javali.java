
public class Javali{
    private final int idCozinheiro;
    private final int numOrdem;

    public Javali(int idCozinheiro, int numOrdem){
        this.idCozinheiro = idCozinheiro;
        this.numOrdem = numOrdem;
    }

    public int getIdCozinheiro(){
        return idCozinheiro;
    }

    public int getNumOrdem(){
        return numOrdem;
    }
}